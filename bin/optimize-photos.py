#!/usr/bin/env python3
"""Resize and recompress gallery photographs for the web.

Camera originals are 20+ megapixels and 5-25 MB each. The gallery never displays
more than about 2000px on the long edge (the lightbox on a retina screen), so
everything beyond that is bytes the visitor downloads and cannot see.

Run after adding photographs:

    python3 bin/optimize-photos.py                  # optimize in place
    python3 bin/optimize-photos.py --backup DIR     # copy originals out first
    python3 bin/optimize-photos.py --dry-run        # report, change nothing

Already-optimized files are skipped, so it is safe to re-run: repeated JPEG
recompression degrades an image, and this avoids it.
"""

import argparse
import io
import os
import shutil
import sys

try:
    from PIL import Image, ImageOps
except ImportError:
    sys.exit("Pillow is required:  python3 -m pip install Pillow")

PHOTO_DIR = os.path.join("assets", "img", "photos")
DIMENSIONS_FILE = os.path.join("_data", "photo_dimensions.yml")
MAX_EDGE = 2000  # px on the long edge
QUALITY = 82  # JPEG quality; 82 is visually transparent for photographs
SKIP_BYTES = 900_000  # already small enough to leave alone


def optimize(path, dry_run=False):
    before = os.path.getsize(path)
    with Image.open(path) as im:
        # Bake in the EXIF orientation flag before metadata is dropped, or
        # portrait shots taken on a phone come out sideways.
        im = ImageOps.exif_transpose(im)
        longest = max(im.size)

        if longest <= MAX_EDGE and before <= SKIP_BYTES:
            return before, before, "skipped (already small)"

        if longest > MAX_EDGE:
            scale = MAX_EDGE / longest
            im = im.resize(
                (round(im.width * scale), round(im.height * scale)), Image.LANCZOS
            )

        if im.mode not in ("RGB", "L"):
            im = im.convert("RGB")

        if dry_run:
            return before, before, "would optimize"

        # icc_profile is carried over so wide-gamut shots keep their colour;
        # every other EXIF tag is dropped, which also strips GPS coordinates.
        im.save(
            path,
            "JPEG",
            quality=QUALITY,
            optimize=True,
            progressive=True,
            icc_profile=im.info.get("icc_profile"),
        )

    return before, os.path.getsize(path), "optimized"


def write_dimensions(names):
    """Record each photograph's pixel size for the gallery layout.

    The gallery balances its columns before any image has loaded - it has to,
    because lazy-loaded images below the fold never report a size until they
    are scrolled into view. Knowing width and height up front also means the
    tiles reserve the right space, so the page never jumps as photos arrive.
    """
    lines = [
        "# Generated by bin/optimize-photos.py - do not edit by hand.",
        "# Pixel dimensions of each file in assets/img/photos/, used by the",
        "# gallery to lay out and size tiles before the images load.",
        "",
    ]
    for n in names:
        with Image.open(os.path.join(PHOTO_DIR, n)) as im:
            lines.append('"%s": [%d, %d]' % (n, im.width, im.height))
    with io.open(DIMENSIONS_FILE, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\nWrote %s (%d photographs)" % (DIMENSIONS_FILE, len(names)))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--backup", metavar="DIR", help="copy originals here first")
    ap.add_argument("--dry-run", action="store_true", help="report only")
    args = ap.parse_args()

    if not os.path.isdir(PHOTO_DIR):
        sys.exit("Run this from the repository root (%s not found)" % PHOTO_DIR)

    names = sorted(
        f for f in os.listdir(PHOTO_DIR) if f.lower().endswith((".jpg", ".jpeg"))
    )
    if not names:
        sys.exit("No photographs found in %s" % PHOTO_DIR)

    if args.backup and not args.dry_run:
        os.makedirs(args.backup, exist_ok=True)
        for n in names:
            dest = os.path.join(args.backup, n)
            if not os.path.exists(dest):
                shutil.copy2(os.path.join(PHOTO_DIR, n), dest)
        print("Originals copied to %s\n" % args.backup)

    total_before = total_after = 0
    print("%-34s %10s %10s   %s" % ("file", "before", "after", "result"))
    print("-" * 74)
    for n in names:
        before, after, note = optimize(os.path.join(PHOTO_DIR, n), args.dry_run)
        total_before += before
        total_after += after
        print("%-34s %9.1fMB %9.1fMB   %s" % (n, before / 1e6, after / 1e6, note))

    print("-" * 74)
    saved = total_before - total_after
    pct = (saved / total_before * 100) if total_before else 0
    print(
        "%-34s %9.1fMB %9.1fMB   %.0f%% smaller"
        % ("%d files" % len(names), total_before / 1e6, total_after / 1e6, pct)
    )

    if not args.dry_run:
        write_dimensions(names)


if __name__ == "__main__":
    main()
